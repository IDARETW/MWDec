"""Generate src/writers_<build>.inc from a writer descriptor.

The descriptor is the JSON produced by the research tooling (one entry per
writer routine: where its range list, its stash and its key are, and which
decode variant it uses), plus the order in which they must be applied.

The descriptor was built from a memory dump, in which some stashes had
already been prepared by a writer that ran before the dump was taken. From
the at-rest state of the shipped file those writers have to run too. They
are named with --first and are emitted ahead of everything else.

A dump also shows each on-demand range in whichever state the last writer
left it, so it cannot always tell a decryptor from the routine that
re-encrypts behind it. --amend names a JSON file with what a run of every
routine on the decrypted file showed instead:

    "stream"      {writer id: range list}   the list the writer really uses
    "reclassify"  [writer id, ...]          descriptor entries filed as
                                            re-encryptors that are decryptors
    "append"      [{id, variant, stream, stash, key_src}, ...]
                                            decryptors the descriptor lacks

Amended writers are emitted last, in the order given: they read their
stashes from the image as every earlier writer leaves it.

    py -3 gen_writers.py <descriptor.json> <out.inc> [--first 0xID,0xID,...] [--amend amend.json]
"""
import json
import sys

VARIANT = {"xor_rip": "Xor", "sub_rip": "Sub", "xor_auto": "XorAuto", "mul_rol": "MulRol"}

args = sys.argv[1:]
first = []
if "--first" in args:
    i = args.index("--first")
    first = [int(x, 16) for x in args[i + 1].split(",")]
    del args[i:i + 2]
amend = {}
if "--amend" in args:
    i = args.index("--amend")
    amend = json.load(open(args[i + 1]))
    del args[i:i + 2]
desc = json.load(open(args[0]))
every = {}
for cat in ("writers", "reencrypt_writers", "unresolved_writers"):
    for w in desc.get(cat, []):
        every.setdefault(int(w["id"], 16), w)
for wid, stream in amend.get("stream", {}).items():
    every[int(wid, 16)] = dict(every[int(wid, 16)], stream=stream)


def row(w, stash):
    return "{0x%08X, %s, WriterVariant::%s, 0x%08X, 0x%08X, 0x%08X}," % (
        int(w["id"], 16), "true" if stash else "false", VARIANT[w["variant"]],
        int(w["stream"], 16), int(w["stash"], 16), int(w["key_src"], 16))


lines = ["// Generated by tools/gen_writers.py. One row per writer, in application order:",
         "// {routine, writes a stash, variant, range list, stash, key}"]
for wid in first:
    lines.append(row(every[wid], True))
for wid in desc["order"]:
    w = every[int(wid, 16)]
    lines.append(row(w, w["role"] == "stash_layer"))
extra = [every[int(wid, 16)] for wid in amend.get("reclassify", [])] + list(amend.get("append", []))
for w in extra:
    lines.append(row(w, False))
open(args[1], "w", newline="\n").write("\n".join(lines) + "\n")
print("wrote %d writers (%d first, %d amended) to %s" % (
    len(desc["order"]) + len(first) + len(extra), len(first), len(extra), args[1]))
